	private PixelIcons() {
	}

	public static String[] forModule(Module module) {
		String[] icon = MODULES.get(module.id);
		return icon != null ? icon : SNOWFLAKE;
	}

	/** Draws an icon with its top-left at (x, y), each pixel scale x scale, centred in a 12x12 box. */
	public static void draw(Draw d, String[] icon, int x, int y, int scale, int color) {
		int rows = icon.length;
		int cols = 0;
		for (String row : icon) cols = Math.max(cols, row.length());
		int ox = x + (SIZE - cols) * scale / 2;
		int oy = y + (SIZE - rows) * scale / 2;
		for (int r = 0; r < rows; r++) {
			String line = icon[r];
			int start = -1;
			for (int c = 0; c <= line.length(); c++) {
				boolean on = c < line.length() && line.charAt(c) == '#';
				if (on && start < 0) start = c;
				if (!on && start >= 0) {
					d.fill(ox + start * scale, oy + r * scale, ox + c * scale, oy + (r + 1) * scale, color);
					start = -1;
				}
			}
		}
	}
